using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace PlaxionMediator.SourceGenerators;

internal static class SourceEmitter
{
    /// <summary>
    /// Above this many request handlers, generic <c>Send</c> uses a static Type→id map + integer jump table
    /// instead of an N-way type-pattern switch. Small N keeps type patterns (faster for the common 1-type case).
    /// </summary>
    private const int TypeMapDispatchThreshold = 16;

    public static string EmitRegistration(GenerationModel model)
    {
        StringBuilder sb = new();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using PlaxionMediator.Abstractions;");
        sb.AppendLine("using PlaxionMediator.Core;");
        sb.AppendLine("using PlaxionMediator;");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection.Extensions;");
        sb.AppendLine();
        sb.Append("namespace ").Append(model.RootNamespace).AppendLine(".Generated;");
        sb.AppendLine();
        sb.AppendLine("internal static class PlaxionMediatorRegistration");
        sb.AppendLine("{");
        sb.AppendLine("    [ModuleInitializer]");
        sb.AppendLine("    internal static void Initialize()");
        sb.AppendLine("    {");
        sb.AppendLine("        PlaxionMediatorGeneratedRegistrationBridge.Register = Register;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public static void Register(IServiceCollection services, PlaxionMediatorOptions options)");
        sb.AppendLine("    {");

        foreach (RequestHandlerModel handler in model.RequestHandlers)
        {
            sb.Append("        services.TryAdd(new ServiceDescriptor(typeof(IRequestHandler<")
                .Append(handler.RequestFullyQualifiedName)
